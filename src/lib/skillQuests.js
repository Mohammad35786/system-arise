  export function getSkillQuestsForDomains(domains) {
    if (!domains || domains.length === 0) return []
    const available = []
    domains.forEach(domain => {
      const quests = SKILL_QUEST_LIBRARY[domain] || []
      quests.forEach(q => available.push({ ...q, domain }))
    })
    return available
  }
  
  export function getDailySkillQuest(domains, completedIds = []) {
    const all = getSkillQuestsForDomains(domains)
    const incomplete = all.filter(q => !completedIds.includes(q.id))
    if (incomplete.length === 0) return all[0] || null
    // Rotate through domains evenly
    const today = new Date().getDay()
    return incomplete[today % incomplete.length]
  }